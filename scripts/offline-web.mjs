import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import path from "node:path";

// Package only the exported app shell. Pet documents stay in local saved-life storage;
// no pet, care, seed or development state is stored in the service-worker cache.
const root = path.resolve("dist");
const base =
  `/${(process.env.INFIPET_BASE_URL || "").replace(/^\/+|\/+$/g, "")}/`.replace(
    /\/+/g,
    "/",
  );
// Public deployment identity has no player data. Read the checked-out commit,
// including workflow_run deployments, rather than the triggering default SHA.
await writeFile(path.join(root,"release.json"),JSON.stringify({
  commit:execFileSync("git",["rev-parse","HEAD"],{encoding:"utf8"}).trim(),
  anatomicalClock:"daily-365-v1",finalCheck:365,
})+"\n");
const files = [];
async function visit(dir) {
  for (const entry of await readdir(path.join(root, dir), {
    withFileTypes: true,
  })) {
    const relative = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) await visit(relative);
    else if (relative !== "service-worker.js" && !relative.endsWith(".map"))
      files.push(relative);
  }
}
await visit("");
files.sort();
let html = await readFile(path.join(root, "index.html"), "utf8");
const registration = `<script>if('serviceWorker' in navigator){navigator.serviceWorker.register(${JSON.stringify(base + "service-worker.js")},{scope:${JSON.stringify(base)}}).catch(function(){/* Online play remains available if caching is blocked. */});}</script>`;
html = html.replace("</body>", `${registration}</body>`);
await writeFile(path.join(root, "index.html"), html);
const hash = createHash("sha256");
for (const file of files)
  hash.update(file).update(await readFile(path.join(root, file)));
const cache = "infipet-shell-" + hash.digest("hex").slice(0, 16);
const urls = files.map((file) => base + file);
await writeFile(
  path.join(root, "service-worker.js"),
  `// Generated by scripts/offline-web.mjs. Contains no player state.
const CACHE = ${JSON.stringify(cache)};
const SHELL = ${JSON.stringify(urls)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(SHELL)));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('infipet-shell-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET' || new URL(event.request.url).origin !== self.location.origin) return;
  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).catch(() => caches.open(CACHE).then(cache => cache.match(${JSON.stringify(base + "index.html")}))));
  } else if (SHELL.includes(new URL(event.request.url).pathname)) {
    event.respondWith(caches.open(CACHE).then(cache => cache.match(event.request)).then(hit => hit || fetch(event.request)));
  }
});
`,
);
console.log(`Offline shell: ${files.length} files under ${base}`);
