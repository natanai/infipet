/** Decorative pixel glyph; its button supplies the accessible label. */
export function PixelIcon({
  name,
  size = 24,
  color = T.text,
}: {
  name: PixelIconName;
  size?: number;
  color?: string;
}) {
  const path = ART[name]
    .flatMap((row, y) =>
      [...row].flatMap((cell, x) =>
        cell === "#" ? [`M${x} ${y}h1v1h-1z`] : [],
      ),
    )
    .join("");
  return (
    <Svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      {...(Platform.OS === "web"
        ? { "aria-hidden": true }
        : { accessible: false })}
      pointerEvents="none"
    >
      <Path d={path} fill={color} />
    </Svg>
  );
}

export default PixelIcon;
